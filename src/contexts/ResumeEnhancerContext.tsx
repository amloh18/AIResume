// State Interface
export interface ResumeEnhancerState {
  // Mode and navigation
  mode: 'create' | 'edit';
  currentStep: 1 | 2 | 3 | 4 | 5;

  // CV identification
  cvId?: string;
  cvType: 'master' | 'journey' | 'standalone';
  cvTitle: string;

  // CV data
  cvData: UnifiedCVDataStructure;

  // Template
  selectedTemplate: ITemplate | null;

  // Role context
  targetRole: string;
  seniorityLevel: string;

  // Job/Journey context
  jobData?: any;
  journeyId?: string;

  // AI Analysis
  surgeonAnalysis: { score: number; fixes: SurgicalFix[] } | null;
  isAnalyzing: boolean;

  // Legacy/overlay state (used by ResumeEnhancerClient + overlays)
  showProfilerModal: boolean;
  showSurgeonOverlay: boolean;
  showPreviewOverlay: boolean;
  cvScore: number;
  surgicalFixes: SurgicalFix[];

  // Report / Review & Fix mode (Step 3)
  fixAnnotations: FixAnnotation[];
  reportOpen: boolean;
  reviewMode: boolean;
  activeFixId?: string;

  // Save state
  isSaving: boolean;
  saveError: string | null;

  // Session tracking
  sessionStartTime: number;
  stepStartTimes: Record<number, number>;

  // Loop breaker state
  currentCVHash?: string; // Hash of current CV to detect fundamental changes
  suppressedFixHashes: string[]; // List of suppressed fix signature hashes

  // Career Ecosystem: Master CV & Fresher Mode
  isUserMaster: boolean; // Is this THE user's single Master CV
  fresherMode: boolean; // Education/Projects first layout (no work experience)
  hasMasterCV: boolean; // Does user already have a Master CV
  isFirstCVCreation: boolean; // Is this the first CV the user is creating (0 CVs exist)
  enforceMasterCVMode: boolean; // Lock UI to Master CV mode when creating first CV

  // Career Ecosystem: ATS Score & Template Cap
  atsScoreCap: number; // Template-based cap (default 100, creative = 70)
  atsScore: number; // ATS match score for Journey CVs (0-100)

  // Career Ecosystem: Keyword Gap Analysis (Journey mode)
  keywordGaps: KeywordGap[]; // Missing JD keywords
  keywordGapAnalysis: KeywordGapAnalysisResult | null; // Full analysis result
  isAnalyzingKeywords: boolean; // Loading state for keyword analysis

  // Career Ecosystem: Auto-generated Cover Letter
  autoGeneratedCoverLetter?: string; // Draft cover letter body
  coverLetterId?: string; // ID of created cover letter

  // Career Ecosystem: JD Input (for Step 1 Journey flow)
  jdText: string; // Raw JD text pasted by user
  jdWordCount: number; // Word count for validation

  // Analysis Mode (computed from cvType, role, and JD)
  analysisMode: AnalysisMode;

  // Enhanced Analysis Mode with Validation (NEW)
  analysisModeInfo: AnalysisModeInfo | null;
  lastAnalysisContext: {
    mode: AnalysisMode;
    roleHash: string;
    jdHash: string;
  } | null;
  modeTransitionWarnings: string[];
  modeTransitionData: { fromMode: AnalysisMode; toMode: AnalysisMode; transitionType: string } | null;

  // Score multipliers and breakdowns (for enhance.md formulas)
  cvScoreMultiplier: number;           // V factor (0.2 or 1.0)
  cvScoreBreakdown: Record<string, number> | null; // C, I, Q, F, R
  cvPenaltyReasons: string[];          // Reasons for score penalty
  atsScoreMultiplier: number;          // P factor (0.1 or 1.0)
  atsScoreBreakdown: Record<string, number> | null; // K, F, S, R, C
  atsScoreContext: 'jd-specific' | 'industry-general';

  // Simulated CV toggle and strategic fix data
  showSimulatedCV: boolean;
  strategicFixAvailable: boolean;
  strategicFixData: any | null;        // CV data with strategic projects
  authenticOptData: any | null;        // Authentic optimization data
  annotationLog: { path: string; action: string; reason: string }[];
  nextSteps: string[];

  // Document Formatting Preferences
  dateFormat: DateFormatStyle;  // User-selected date format for CV
  paperSize: PaperSize;         // Detected or user-selected paper size

  // Centralized View State (Phase 3)
  isJobSidebarOpen: boolean;
  isTemplateOverlayOpen: boolean;

  // Mori Chat Mode
  moriChatMode: boolean;
}

