// Reducer
function resumeEnhancerReducer(
  state: ResumeEnhancerState,
  action: ResumeEnhancerAction
): ResumeEnhancerState {
  switch (action.type) {
    case 'SET_JOB_SIDEBAR_OPEN':
      return { ...state, isJobSidebarOpen: action.payload };
    case 'SET_TEMPLATE_OVERLAY_OPEN':
      return { ...state, isTemplateOverlayOpen: action.payload };
    case 'SET_MORI_CHAT_MODE':
      return { ...state, moriChatMode: action.payload };
    case 'SET_MODE':
      return { ...state, mode: action.payload };

    case 'SET_STEP':
      return {
        ...state,
        currentStep: action.payload,
        stepStartTimes: {
          ...state.stepStartTimes,
          [action.payload]: Date.now()
        }
      };

    case 'SET_CURRENT_STEP':
      return {
        ...state,
        currentStep: action.payload,
        stepStartTimes: {
          ...state.stepStartTimes,
          [action.payload]: Date.now()
        }
      };

    case 'SET_CV_ID':
      return { ...state, cvId: action.payload };

    case 'SET_CV_TYPE':
      return { ...state, cvType: action.payload };

    case 'SET_CV_TITLE':
      return { ...state, cvTitle: action.payload };

    case 'UPDATE_CV_DATA':
      return {
        ...state,
        cvData: {
          ...state.cvData,
          ...action.payload
        }
      };

    case 'SET_CV_DATA':
      return { ...state, cvData: action.payload };

    case 'SET_TEMPLATE':
      return { ...state, selectedTemplate: action.payload };

    case 'SET_SELECTED_TEMPLATE':
      return { ...state, selectedTemplate: action.payload };

    case 'SET_ROLE_CONTEXT':
      return {
        ...state,
        targetRole: action.payload.targetRole,
        seniorityLevel: action.payload.seniorityLevel
      };

    case 'SET_TARGET_ROLE':
      return { ...state, targetRole: action.payload };

    case 'SET_SENIORITY_LEVEL':
      return { ...state, seniorityLevel: action.payload };

    case 'SET_JOB_DATA':
      return { ...state, jobData: action.payload };

    case 'SET_JOURNEY_ID':
      return { ...state, journeyId: action.payload };

    case 'CONVERT_TO_JOURNEY':
      return {
        ...state,
        cvType: 'journey',
        journeyId: action.payload.journeyId,
        jobData: action.payload.jobData,
        coverLetterId: action.payload.coverLetterId,
        autoGeneratedCoverLetter: action.payload.coverLetterDraft
      };

    case 'SET_SURGEON_ANALYSIS':
      return {
        ...state,
        surgeonAnalysis: action.payload,
        cvScore: action.payload.score || 0,
        surgicalFixes: (action.payload.fixes || []).map((f) => ({ ...f, status: f.status ?? 'pending' })),
        isAnalyzing: false
      };

    case 'SET_FIX_ANNOTATIONS':
      return { ...state, fixAnnotations: action.payload };

    case 'SET_REPORT_OPEN':
      return { ...state, reportOpen: action.payload };

    case 'SET_REVIEW_MODE':
      return { ...state, reviewMode: action.payload };

    case 'SET_ACTIVE_FIX':
      return { ...state, activeFixId: action.payload };

    case 'MARK_FIX_APPLIED':
      return {
        ...state,
        fixAnnotations: state.fixAnnotations.map((f) =>
          f.id === action.payload ? { ...f, status: 'applied' } : f
        ),
        surgicalFixes: (state.surgicalFixes || []).map((f) =>
          f.id === action.payload ? { ...f, status: 'accepted' } : f
        )
      };

    case 'MARK_FIX_DISMISSED':
      return {
        ...state,
        fixAnnotations: state.fixAnnotations.map((f) =>
          f.id === action.payload ? { ...f, status: 'dismissed' } : f
        ),
        surgicalFixes: (state.surgicalFixes || []).map((f) =>
          f.id === action.payload ? { ...f, status: 'rejected' } : f
        )
      };

    case 'MARK_FIX_SUPPRESSED':
      return {
        ...state,
        fixAnnotations: state.fixAnnotations.map((f) =>
          f.id === action.payload.fixId
            ? {
              ...f,
              status: 'suppressed',
              suppression: {
                timestamp: Date.now(),
                reason: action.payload.reason,
                userId: '' // Will be set by the service
              },
              fixSignatureHash: action.payload.fixSignatureHash
            }
            : f
        ),
        suppressedFixHashes: action.payload.fixSignatureHash
          ? [...state.suppressedFixHashes.filter(h => h !== action.payload.fixSignatureHash), action.payload.fixSignatureHash]
          : state.suppressedFixHashes
      };

    case 'MARK_FIX_SEMANTIC_MATCH':
      return {
        ...state,
        fixAnnotations: state.fixAnnotations.map((f) =>
          f.id === action.payload.fixId
            ? {
              ...f,
              status: 'semantic_match',
              semanticMatch: {
                requiredTerm: f.replacementText || f.originalText,
                foundTerm: action.payload.foundTerm,
                confidenceScore: action.payload.confidence
              }
            }
            : f
        )
      };

    case 'SET_ANALYZING':
      return { ...state, isAnalyzing: action.payload };

    case 'SET_SHOW_PROFILER_MODAL':
      return { ...state, showProfilerModal: action.payload };

    case 'SET_SHOW_SURGEON_OVERLAY':
      return { ...state, showSurgeonOverlay: action.payload };

    case 'SET_SHOW_PREVIEW_OVERLAY':
      return { ...state, showPreviewOverlay: action.payload };

    case 'APPLY_SURGICAL_FIX':
      return {
        ...state,
        surgicalFixes: (state.surgicalFixes || []).map((f) =>
          f.id === action.payload ? { ...f, status: 'accepted' } : f
        ),
        fixAnnotations: state.fixAnnotations.map((f) =>
          f.id === action.payload ? { ...f, status: 'applied' } : f
        )
      };

    case 'UPDATE_SURGICAL_FIX_STATUS':
      return {
        ...state,
        surgicalFixes: (state.surgicalFixes || []).map((f) =>
          f.id === action.payload.id ? { ...f, status: action.payload.status } : f
        )
      };

    case 'SET_SAVING':
      return { ...state, isSaving: action.payload };

    case 'SET_SAVE_ERROR':
      return { ...state, saveError: action.payload };

    case 'LOAD_CV':
      return {
        ...state,
        mode: 'edit',
        currentStep: 3, // Skip to builder/surgeon for editing
        cvId: action.payload.cvId,
        cvType: action.payload.cvType,
        cvTitle: action.payload.cvTitle,
        cvData: action.payload.cvData,
        selectedTemplate: action.payload.template || state.selectedTemplate,
        journeyId: action.payload.journeyId,
        jobData: action.payload.jobData,
        coverLetterId: action.payload.coverLetterId, // Load cover letter ID for journey CVs
        cvScore: 0,
        surgicalFixes: [],
        showPreviewOverlay: false,
        showSurgeonOverlay: false,
        showProfilerModal: false,
        // Reset report state when switching CVs
        fixAnnotations: [],
        reportOpen: false,
        reviewMode: false,
        activeFixId: undefined
      };

    case 'RESET_STATE':
      return {
        ...initialState,
        sessionStartTime: Date.now(),
        stepStartTimes: { 1: Date.now() },
        currentCVHash: undefined,
        suppressedFixHashes: []
      };

    // Career Ecosystem Actions
    case 'SET_IS_USER_MASTER':
      return { ...state, isUserMaster: action.payload };

    case 'SET_FRESHER_MODE':
      return { ...state, fresherMode: action.payload };

    case 'SET_HAS_MASTER_CV':
      return { ...state, hasMasterCV: action.payload };

    case 'SET_IS_FIRST_CV_CREATION':
      return { ...state, isFirstCVCreation: action.payload };

    case 'SET_ENFORCE_MASTER_CV_MODE':
      // When enforcing master CV mode, also set cvType to master
      return {
        ...state,
        enforceMasterCVMode: action.payload,
        cvType: action.payload ? 'master' : state.cvType
      };

    case 'SET_ATS_SCORE_CAP':
      return { ...state, atsScoreCap: action.payload };

    case 'SET_ATS_SCORE':
      return { ...state, atsScore: Math.min(action.payload, state.atsScoreCap) };

    case 'SET_KEYWORD_GAPS':
      return { ...state, keywordGaps: action.payload };

    case 'SET_KEYWORD_GAP_ANALYSIS':
      return {
        ...state,
        keywordGapAnalysis: action.payload,
        keywordGaps: action.payload?.gaps || [],
        atsScore: action.payload ? Math.min(action.payload.matchScore, state.atsScoreCap) : state.atsScore,
        isAnalyzingKeywords: false
      };

    case 'SET_ANALYZING_KEYWORDS':
      return { ...state, isAnalyzingKeywords: action.payload };

    case 'UPDATE_KEYWORD_GAP':
      return {
        ...state,
        keywordGaps: state.keywordGaps.map((gap) =>
          gap.keyword === action.payload.keyword
            ? { ...gap, ...action.payload.updates }
            : gap
        )
      };

    case 'SET_AUTO_COVER_LETTER':
      return {
        ...state,
        autoGeneratedCoverLetter: action.payload.draft,
        coverLetterId: action.payload.coverLetterId || state.coverLetterId
      };

    case 'SET_JD_TEXT':
      const wordCount = action.payload.trim().split(/\s+/).filter(Boolean).length;
      return {
        ...state,
        jdText: action.payload,
        jdWordCount: wordCount
      };

    case 'CLEAR_JD_TEXT':
      return {
        ...state,
        jdText: '',
        jdWordCount: 0
      };

    // Validation Actions (NEW)
    case 'SET_ANALYSIS_MODE_INFO':
      return {
        ...state,
        analysisModeInfo: action.payload,
        analysisMode: action.payload.mode
      };

    case 'INVALIDATE_ANALYSIS':
      return {
        ...state,
        surgeonAnalysis: null,
        cvScore: 0,
        surgicalFixes: [],
        fixAnnotations: []
      };

    case 'SET_MODE_WARNINGS':
      return { ...state, modeTransitionWarnings: action.payload };

    case 'CLEAR_MODE_WARNINGS':
      return { ...state, modeTransitionWarnings: [] };

    case 'SET_MODE_TRANSITION_DATA':
      return { ...state, modeTransitionData: action.payload };

    case 'UPDATE_LAST_ANALYSIS_CONTEXT':
      return {
        ...state,
        lastAnalysisContext: action.payload
      };

    // Score multiplier and simulated CV actions (NEW for enhance.md)
    case 'SET_SCORE_MULTIPLIERS':
      return {
        ...state,
        cvScoreMultiplier: action.payload.cvMultiplier,
        atsScoreMultiplier: action.payload.atsMultiplier
      };

    case 'SET_SCORE_BREAKDOWNS':
      return {
        ...state,
        cvScoreBreakdown: action.payload.cvBreakdown,
        atsScoreBreakdown: action.payload.atsBreakdown,
        cvPenaltyReasons: action.payload.cvPenaltyReasons || []
      };

    case 'SET_ATS_SCORE_CONTEXT':
      return {
        ...state,
        atsScoreContext: action.payload
      };

    case 'TOGGLE_SIMULATED_CV':
      return {
        ...state,
        showSimulatedCV: action.payload
      };

    case 'SET_STRATEGIC_FIX_DATA':
      return {
        ...state,
        strategicFixData: action.payload.strategicFix,
        authenticOptData: action.payload.authenticOpt,
        strategicFixAvailable: action.payload.required,
        annotationLog: action.payload.annotationLog || [],
        nextSteps: action.payload.nextSteps || []
      };

    // Document Formatting Actions
    case 'SET_DATE_FORMAT':
      return {
        ...state,
        dateFormat: action.payload
      };

    case 'SET_PAPER_SIZE':
      return {
        ...state,
        paperSize: action.payload
      };

    default:
      return state;
  }
}

